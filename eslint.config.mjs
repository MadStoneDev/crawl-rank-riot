// ESLint 9 flat config for the crawler. Runs the lint gate CLAUDE.md asks for
// (`npm run lint`) non-interactively over the TypeScript sources. Kept to the
// non-type-checked recommended set: it catches real bugs (unused vars, unsafe
// comparisons, misused promises-of-the-cheap-kind) without the slow full
// type-aware pass, so it is fast enough to run before every commit.
import js from "@eslint/js";
import tseslint from "typescript-eslint";
import globals from "globals";

export default tseslint.config(
  {
    // Build output, deps and generated artefacts are never linted.
    // database.types.ts is generated by supatypes and must not be hand-edited.
    ignores: [
      "dist/**",
      "node_modules/**",
      "coverage/**",
      "src/database.types.ts",
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    files: ["src/**/*.ts", "test/**/*.ts", "scripts/**/*.{ts,mjs}"],
    languageOptions: {
      globals: { ...globals.node },
    },
    rules: {
      // `any` is used deliberately at external boundaries (Supabase rows,
      // Express error handlers, test mocks) and `tsc --strict` is the real
      // type-safety gate, so surface it as a warning — visible on every run,
      // not a commit-blocker. Tighten to "error" once the boundaries are typed.
      "@typescript-eslint/no-explicit-any": "warn",
      // Allow intentionally-unused args/vars when prefixed with _ (common in
      // Express handlers: (req, _res, next) and in destructuring rest).
      "@typescript-eslint/no-unused-vars": [
        "error",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
        },
      ],
    },
  },
);
